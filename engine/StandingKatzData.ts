/**
 * Validate that a Pr, Tr pair is within the Standing-Katz table range
 */
export function isInStandingKatzRange(Pr: number, Tr: number): boolean {
  const minTr = STANDING_KATZ_DATA.Tr_values[0];
  const maxTr = STANDING_KATZ_DATA.Tr_values[STANDING_KATZ_DATA.Tr_values.length - 1];
  const minPr = STANDING_KATZ_DATA.Pr_values[0];
  const maxPr = STANDING_KATZ_DATA.Pr_values[STANDING_KATZ_DATA.Pr_values.length - 1];

  return Pr >= minPr && Pr <= maxPr && Tr >= minTr && Tr <= maxTr;
}

/**
 * Get the range of validity for Standing-Katz data
 */
export function getStandingKatzRange(): {
  Pr_min: number;
  Pr_max: number;
  Tr_min: number;
  Tr_max: number;
} {
  return {
    Pr_min: STANDING_KATZ_DATA.Pr_values[0],
    Pr_max: STANDING_KATZ_DATA.Pr_values[STANDING_KATZ_DATA.Pr_values.length - 1],
    Tr_min: STANDING_KATZ_DATA.Tr_values[0],
    Tr_max: STANDING_KATZ_DATA.Tr_values[STANDING_KATZ_DATA.Tr_values.length - 1]
  };
}
