/**
 * Standing-Katz Z-Factor Chart Data
 *
 * Digitized from Standing, M.B., & Katz, D.L. (1942)
 * "Density of Natural Gases." Transactions of the AIME, 146, 140-149.
 *
 * This is the reference standard for gas compressibility factors.
 * All correlation equations are fitted to this data.
 *
 * Data format: Z[Tr_index][Pr_index]
 * Valid range: 0.2 ≤ Pr ≤ 15, 1.0 ≤ Tr ≤ 3.0
 * Extended subcritical: 0.7 ≤ Tr < 1.0 (from Dranchuk et al. extension)
 *
 * Accuracy: ±0.1-0.5% (reference standard)
 */

